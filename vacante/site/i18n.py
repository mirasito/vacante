def t(lang: str, text: str, **values) -> str:
    """Строка интерфейса на языке lang; {name} в строке заменяются значениями."""
    out = UI.get(text, text) if lang == "kk" else text
    return out.format(**values) if values else out


def title(v: Vacancy, lang: str) -> str:
    """Название вакансии: казахское с hh.kz или перевод должностей из разбора («Официант, Повар» → «Даяшы, Аспаз»)."""
    if lang != "kk":
        return v.title
    if v.title_kk:
        return v.title_kk
    parts = v.title.split(", ")
    return ", ".join(TITLES_KK[p] for p in parts) if all(p in TITLES_KK for p in parts) else v.title


def perk(name: str, lang: str) -> str:
    return PERKS_KK.get(name, name) if lang == "kk" else name
